"""Write app/precache-manifest.js: the offline app-shell file list + a content hash version.

Run after changing any app file:  python tools/build_precache.py
Lessons are excluded on purpose: they are private and cached only after login.
"""
import hashlib
import pathlib
import sys

APP = pathlib.Path(__file__).resolve().parent.parent / 'app'
EXCLUDE_DIRS = {'lessons', 'tests', 'legacy'}
EXCLUDE_PREFIX = ('assets/reference/',)
EXCLUDE_NAMES = {'sw.js', 'precache-manifest.js', '.tmp-ignore'}
PRIVATE_FILES = {'assets/imported/' + n for n in ('common.css', 'foundation.css', 'foundation.js', 'learning-asides.js', 'learning-progress.js')}


def wanted(rel: str) -> bool:
    parts = rel.split('/')
    if rel in PRIVATE_FILES:
        return False
    if parts[0] in EXCLUDE_DIRS or rel.startswith(EXCLUDE_PREFIX):
        return False
    if parts[-1] in EXCLUDE_NAMES or rel.endswith('.md') or parts[-1].startswith('.'):
        return False
    return True


def main() -> int:
    files = sorted(p.relative_to(APP).as_posix() for p in APP.rglob('*') if p.is_file())
    files = [f for f in files if wanted(f)]
    digest = hashlib.sha256()
    for f in files:
        digest.update(f.encode())
        digest.update((APP / f).read_bytes())
    digest.update((APP / 'sw.js').read_bytes())
    version = digest.hexdigest()[:12]
    listing = ',\n    '.join(f"'{f}'" for f in ['./'] + files)
    (APP / 'precache-manifest.js').write_text(
        "/* Generated by tools/build_precache.py — do not edit by hand. */\n"
        f"self.CS_PRECACHE = {{\n  version: '{version}',\n  files: [\n    {listing}\n  ]\n}};\n",
        encoding='utf-8')
    size = sum((APP / f).stat().st_size for f in files)
    print(f'precache: {len(files)} files, {size / 1024 / 1024:.1f} MB, version {version}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
